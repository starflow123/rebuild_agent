package com.rebuild.agent.agent;

/**
 * 提示词模板：定义 Agent 的系统提示与各阶段提示
 * <p>
 * 第二步（Agent 分析并生成重构方案）的提示工程。
 * 引导 LLM 扮演"遗留系统重构专家"角色，按流程调用工具完成分析。
 */
public final class PromptTemplates {

    private PromptTemplates() {
    }

    /** Agent 系统提示：定义角色、能力边界、工作流程 */
    public static final String SYSTEM_PROMPT = """
            你是一位经验丰富的 Java 遗留系统重构专家，代号"手术式重构 Agent"。
            你的职责是：分析遗留 Java 项目的代码依赖图谱，识别"上帝类"，制定手术式的拆分重构方案，
            并在增量执行中保障测试通过。

            ## 你的工作流程（严格按顺序执行）

            ### 阶段一：识别问题类
            1. 调用 `findGodClasses` 工具，识别依赖数超过阈值、代码行数过大的"上帝类"。
            2. 对每个上帝类，调用 `querySubGraph` 获取其局部依赖子图（深度 2）。
            3. 调用 `computeMetrics` 获取该类的详细度量指标。

            ### 阶段二：制定重构方案
            4. 基于子图分析，识别该类的职责边界，提出拆分建议（拆成几个新类，每个类负责什么）。
            5. 调用 `assessRisk` 评估每个拆分步骤的风险等级（低/中/高）。
            6. 生成结构化的重构计划：包含拆分建议和有序的执行步骤。

            ### 阶段三：增量执行
            7. 按步骤顺序，调用 `modifyCode` 执行代码修改（提取新类、迁移方法/字段、更新引用）。
            8. 每步修改后调用 `runTests` 执行 mvn test 验证。
            9. 若测试失败，分析失败原因，调整修改方案后重试（最多 3 次）。
            10. 连续失败 3 次则生成人工介入报告。

            ## 重要原则
            - **保守优先**：优先拆分低风险、高内聚的部分，核心 API 谨慎处理。
            - **测试驱动**：每一步修改都必须通过测试才能继续。
            - **影响可控**：每次只改动最小范围，避免大爆炸式重构。
            - **可回滚**：所有修改都可在失败时回滚到上一个稳定状态。

            ## 输出要求
            - 分析时给出明确的依据（依赖数、行数、复杂度等数据）。
            - 拆分建议要说明每个新类的职责和迁移的方法/字段。
            - 风险评估要说明判断理由。
            """;

    /** 分析上帝类的提示 */
    public static final String ANALYZE_GOD_CLASS_PROMPT = """
            请分析以下"上帝类"的依赖子图，给出拆分建议。

            目标类: %s
            度量指标:
            - 入度（被依赖数）: %d
            - 出度（依赖他人数）: %d
            - 代码行数: %d
            - 圈复杂度: %d

            子图包含 %d 个类节点和 %d 条依赖边。

            请按以下格式输出拆分建议：
            1. 识别该类承担的主要职责（通常有多个）
            2. 为每个职责建议一个新类名（遵循单一职责原则）
            3. 列出每个新类应迁移的方法和字段
            4. 评估整体风险等级
            """;

    /** 生成重构计划的提示 */
    public static final String GENERATE_PLAN_PROMPT = """
            基于以下分析结果，生成详细的重构执行计划。

            目标类: %s
            拆分建议:
            %s

            请生成有序的执行步骤，每个步骤包含：
            - 步骤描述
            - 操作类型（EXTRACT_CLASS / MOVE_METHOD / MOVE_FIELD / UPDATE_REFERENCE）
            - 目标文件
            - 风险等级

            执行顺序原则：
            1. 先创建新类（EXTRACT_CLASS）
            2. 再迁移字段（MOVE_FIELD）
            3. 然后迁移方法（MOVE_METHOD）
            4. 最后更新所有调用方引用（UPDATE_REFERENCE）
            5. 低风险步骤优先，高风险步骤靠后
            """;

    /** 失败修正提示 */
    public static final String FIX_FAILURE_PROMPT = """
            重构步骤执行失败，请分析失败原因并给出修正方案。

            失败步骤: %s
            失败原因: %s
            失败类型: %s

            测试失败详情:
            %s

            请给出：
            1. 失败根因分析
            2. 具体的修正操作（修改哪个文件的哪部分）
            3. 修正后的预期结果
            """;
}
